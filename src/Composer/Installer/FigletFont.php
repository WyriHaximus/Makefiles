    /** @param array<string, list<string>> $glyphs */
    private function __construct(
        private int $height,
        private array $glyphs,
    ) {
    }

    public static function mini(): self
    {
        return new self(self::HEIGHT, self::miniGlyphs());
    }

    /** @return array<string, list<string>> */
    private static function miniGlyphs(): array
    {
        $glyphs = [];
        foreach (self::MINI_GLYPHS as $character => $rows) {
            $glyphs[(string) $character] = $rows;
        }

        return $glyphs;
    }

    /** @return list<string> */
    public function render(string $text): array
    {
        $output = array_fill(0, $this->height, '');
        $length = strlen($text);

        for ($position = 0; $position < $length; $position++) {
            $character = $text[$position];
            $glyph     = $this->glyphs[$character] ?? $this->glyphs['?'] ?? array_fill(0, $this->height, '');

            for ($row = 0; $row < $this->height; $row++) {
                $output[$row] .= $glyph[$row];

                if ($position >= $length - 1) {
                    continue;
                }

                $output[$row] .= ' ';
            }
        }

        return array_values(array_map(rtrim(...), $output));
    }
